#!/usr/bin/env node
// Phase T2-C — Full 46-character reference extraction.
//
// Same extraction method as extract-reference.js (Phase T2-A), but pulls
// the ENTIRE strokeData object (all 46 gojuon characters) instead of the
// 5-character Pilot subset. Used for character-inventory.js, full golden
// trace generation, and calibrate-stroke-floor-full46.js.
//
// Usage: node tools/tracing-poc/extract-reference-full.js

'use strict';
const fs = require('fs');
const path = require('path');

const REPO_ROOT = path.resolve(__dirname, '..', '..');
const SOURCE_FILE = path.join(REPO_ROOT, 'hiragana-learn.html');
const OUT_DIR = path.join(__dirname, 'fixtures');

function extractStrokeDataObjectLiteral(html) {
  const marker = 'const strokeData = {';
  const start = html.indexOf(marker);
  if (start === -1) throw new Error(`Could not find "${marker}" in ${SOURCE_FILE}`);
  const braceStart = start + marker.length - 1;
  let depth = 0;
  let i = braceStart;
  for (; i < html.length; i++) {
    const ch = html[i];
    if (ch === '{') depth++;
    else if (ch === '}') { depth--; if (depth === 0) { i++; break; } }
  }
  if (depth !== 0) throw new Error('Unbalanced braces while scanning strokeData object literal');
  return html.slice(braceStart, i);
}

function main() {
  const html = fs.readFileSync(SOURCE_FILE, 'utf8');
  const literal = extractStrokeDataObjectLiteral(html);
  // eslint-disable-next-line no-new-func
  const fullStrokeData = new Function(`'use strict'; return (${literal});`)();

  fs.mkdirSync(OUT_DIR, { recursive: true });

  const header =
    '// AUTO-GENERATED by tools/tracing-poc/extract-reference-full.js\n' +
    `// Source of truth: ${path.relative(REPO_ROOT, SOURCE_FILE)} \`strokeData\` (KanjiVG-derived SVG paths, viewBox 0 0 109 109).\n` +
    '// Do NOT hand-edit. Regenerate with: node tools/tracing-poc/extract-reference-full.js\n' +
    `// Generated: ${new Date().toISOString()}\n` +
    `// Character set: all ${Object.keys(fullStrokeData).length} characters in strokeData (full gojuon)\n\n`;

  const jsBody =
    `const TRACING_FULL_REFERENCE = ${JSON.stringify(fullStrokeData, null, 2)};\n\n` +
    "if (typeof module !== 'undefined' && module.exports) {\n" +
    '  module.exports = TRACING_FULL_REFERENCE;\n' +
    "} else if (typeof window !== 'undefined') {\n" +
    '  window.TRACING_FULL_REFERENCE = TRACING_FULL_REFERENCE;\n' +
    '} else {\n' +
    '  globalThis.TRACING_FULL_REFERENCE = TRACING_FULL_REFERENCE;\n' +
    '}\n';

  fs.writeFileSync(path.join(OUT_DIR, 'reference-data-full.generated.js'), header + jsBody, 'utf8');
  fs.writeFileSync(
    path.join(OUT_DIR, 'reference-data-full.generated.json'),
    JSON.stringify(fullStrokeData, null, 2) + '\n',
    'utf8'
  );

  const counts = {};
  Object.values(fullStrokeData).forEach((v) => { counts[v.length] = (counts[v.length] || 0) + 1; });
  console.log(`Extracted ${Object.keys(fullStrokeData).length} characters from ${path.relative(REPO_ROOT, SOURCE_FILE)}.`);
  console.log('Stroke-count distribution:', counts);
  console.log(`Wrote ${path.relative(REPO_ROOT, OUT_DIR)}/reference-data-full.generated.{js,json}`);
}

main();
