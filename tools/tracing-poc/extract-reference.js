#!/usr/bin/env node
// Phase T2-A — Tracing Engine PoC
//
// Extracts strokeData for a fixed set of PoC characters directly from
// hiragana-learn.html (the Source of Truth for KanjiVG stroke paths used
// in production). This script performs NO hand-copy of stroke path data:
// it locates the `const strokeData = {...}` object literal inside the
// production file and evaluates it as JS, then narrows it down to the
// PoC character subset.
//
// Usage:
//   node tools/tracing-poc/extract-reference.js
//
// Output (generated, do not hand-edit):
//   tools/tracing-poc/fixtures/reference-data.generated.js
//   tools/tracing-poc/fixtures/reference-data.generated.json
//
// Regenerate whenever hiragana-learn.html's strokeData changes upstream.

'use strict';
const fs = require('fs');
const path = require('path');

const REPO_ROOT = path.resolve(__dirname, '..', '..');
const SOURCE_FILE = path.join(REPO_ROOT, 'hiragana-learn.html');
const OUT_DIR = path.join(__dirname, 'fixtures');

// PoC character set — see docs/design-system/donomana-tracing-accuracy-design-v1.md Section "T2-A PoC対象文字"
const TARGET_CHARS = ['い', 'く', 'こ', 'あ', 'ま'];

function extractStrokeDataObjectLiteral(html) {
  const marker = 'const strokeData = {';
  const start = html.indexOf(marker);
  if (start === -1) {
    throw new Error(`Could not find "${marker}" in ${SOURCE_FILE}`);
  }
  // Find the matching closing brace for the object literal by brace counting,
  // starting from the '{' right after "const strokeData = ".
  const braceStart = start + marker.length - 1; // index of the opening '{'
  let depth = 0;
  let i = braceStart;
  for (; i < html.length; i++) {
    const ch = html[i];
    if (ch === '{') depth++;
    else if (ch === '}') {
      depth--;
      if (depth === 0) { i++; break; }
    }
  }
  if (depth !== 0) {
    throw new Error('Unbalanced braces while scanning strokeData object literal');
  }
  return html.slice(braceStart, i); // includes surrounding { ... }
}

function main() {
  const html = fs.readFileSync(SOURCE_FILE, 'utf8');
  const literal = extractStrokeDataObjectLiteral(html);

  // The literal is a plain JS object literal (string keys, arrays of
  // {d, label} objects) with no external references, so evaluating it
  // via `new Function` is safe and avoids re-implementing a bespoke
  // JS-object-literal parser just to copy data we already trust.
  // eslint-disable-next-line no-new-func
  const fullStrokeData = new Function(`'use strict'; return (${literal});`)();

  const missing = TARGET_CHARS.filter((k) => !fullStrokeData[k]);
  if (missing.length) {
    throw new Error(`Characters missing from strokeData: ${missing.join(', ')}`);
  }

  const subset = {};
  for (const k of TARGET_CHARS) subset[k] = fullStrokeData[k];

  fs.mkdirSync(OUT_DIR, { recursive: true });

  const header =
    '// AUTO-GENERATED by tools/tracing-poc/extract-reference.js\n' +
    `// Source of truth: ${path.relative(REPO_ROOT, SOURCE_FILE)} \`strokeData\` (KanjiVG-derived SVG paths, viewBox 0 0 109 109).\n` +
    '// Do NOT hand-edit. Regenerate with: node tools/tracing-poc/extract-reference.js\n' +
    `// Generated: ${new Date().toISOString()}\n` +
    `// PoC character set: ${TARGET_CHARS.join(' ')}\n\n`;

  const jsBody =
    `const TRACING_POC_REFERENCE = ${JSON.stringify(subset, null, 2)};\n\n` +
    "if (typeof module !== 'undefined' && module.exports) {\n" +
    '  module.exports = TRACING_POC_REFERENCE;\n' +
    "} else if (typeof window !== 'undefined') {\n" +
    '  window.TRACING_POC_REFERENCE = TRACING_POC_REFERENCE;\n' +
    '} else {\n' +
    '  globalThis.TRACING_POC_REFERENCE = TRACING_POC_REFERENCE;\n' +
    '}\n';

  fs.writeFileSync(path.join(OUT_DIR, 'reference-data.generated.js'), header + jsBody, 'utf8');
  fs.writeFileSync(
    path.join(OUT_DIR, 'reference-data.generated.json'),
    JSON.stringify(subset, null, 2) + '\n',
    'utf8'
  );

  console.log(`Extracted ${TARGET_CHARS.length} characters from ${path.relative(REPO_ROOT, SOURCE_FILE)}:`);
  for (const k of TARGET_CHARS) {
    console.log(`  ${k}: ${subset[k].length} strokes`);
  }
  console.log(`Wrote ${path.relative(REPO_ROOT, OUT_DIR)}/reference-data.generated.{js,json}`);
}

main();
